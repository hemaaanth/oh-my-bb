import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = await build({
  entryPoints: [resolve(root, "public-client.tsx")],
  bundle: true,
  format: "iife",
  minify: true,
  platform: "browser",
  target: "es2022",
  write: false,
  alias: {
    "@get-bb/plugin-sdk/app": resolve(root, "public-sdk.ts"),
  },
  tsconfig: resolve(root, "tsconfig.json"),
});
const source = output.outputFiles[0].text;
const target = resolve(root, "lib/public-review-client.generated.ts");
await mkdir(dirname(target), { recursive: true });
await writeFile(
  target,
  `// Generated by scripts/build-public-client.mjs; committed for managed Git builds.\nexport const PUBLIC_REVIEW_CLIENT_JS = ${JSON.stringify(source)};\n`,
);
