#!/usr/bin/env node
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { dirname, join, posix, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";
import ts from "typescript";

const root = fileURLToPath(new URL("../", import.meta.url));
const vendor = join(root, "provider/vendor/hempi");
const generated = join(root, "provider/hempi-source.generated.ts");
const check = process.argv[2] === "--check";
const local = process.argv[2] === "--local";
if (local && process.argv.length !== 3) throw new Error("--local takes no source checkout or revision.");

function sourceFiles(directory) {
  const files = {};
  const visit = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      const path = join(dir, name);
      const stat = lstatSync(path);
      if (stat.isDirectory()) visit(path);
      else if (stat.isFile()) {
        const key = relative(directory, path).split("\\").join("/");
        if (key !== "REVISION" && !/\.(?:test|spec)\.ts$/.test(key)) files[key] = readFileSync(path, "utf8");
      } else throw new Error(`Hempi source must contain only files and directories: ${path}`);
    }
  };
  visit(directory);
  return files;
}

// Compile the pinned profile-lock dependency closure for the Node host worker.
// Reject non-Node dependencies instead of silently adding a second Pi runtime.
function nodeProfileModules(files) {
  const pending = ["src/optchat/profiles.ts"];
  const emitted = new Set();
  while (pending.length) {
    const path = pending.pop();
    if (emitted.has(path)) continue;
    if (!path.startsWith("src/") || !Object.hasOwn(files, path)) throw new Error(`Missing Hempi Node dependency: ${path}`);
    emitted.add(path);
    const output = ts.transpileModule(files[path], {
      fileName: path,
      compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, newLine: ts.NewLineKind.LineFeed },
      transformers: {
        after: [(context) => {
          const visit = (node) => {
            if (ts.isImportDeclaration(node) && ts.isStringLiteral(node.moduleSpecifier)) {
              const name = node.moduleSpecifier.text;
              if (name.startsWith("node:")) return node;
              if (!name.startsWith(".") || !name.endsWith(".ts")) throw new Error(`Non-Node Hempi profile dependency: ${name}`);
              pending.push(posix.normalize(posix.join(posix.dirname(path), name)));
              return context.factory.updateImportDeclaration(node, node.modifiers, node.importClause,
                context.factory.createStringLiteral(`${name.slice(0, -3)}.mjs`), node.attributes);
            }
            return ts.visitEachChild(node, visit, context);
          };
          return (source) => ts.visitNode(source, visit);
        }],
      },
    });
    files[`node/${path.slice(0, -3)}.mjs`] = output.outputText;
  }
}

function embed(directory, commit) {
  const files = sourceFiles(directory);
  nodeProfileModules(files);
  const contents = Buffer.from(JSON.stringify(files));
  const digest = createHash("sha256").update(contents).digest("hex");
  return `// Generated by scripts/refresh-hempi.mjs. Do not edit.\n// HEMPI_COMMIT is the upstream base; HEMPI_SOURCE_SHA256 identifies the retained local bytes.\nexport const HEMPI_COMMIT = ${JSON.stringify(commit)};\nexport const HEMPI_SOURCE_SHA256 = ${JSON.stringify(digest)};\nexport const HEMPI_FILES_GZIP_BASE64 = ${JSON.stringify(gzipSync(contents).toString("base64"))};\n`;
}

if (check || local) {
  const commit = readFileSync(join(vendor, "REVISION"), "utf8").trim();
  if (!/^[a-f0-9]{40}$/.test(commit)) throw new Error("Invalid retained Hempi base revision.");
  const output = embed(vendor, commit);
  if (check) {
    if (readFileSync(generated, "utf8") !== output)
      throw new Error("Bundled Hempi differs from retained local source. Review local changes, then run scripts/refresh-hempi.mjs --local.");
    console.log(`Bundled Hempi matches retained local source (upstream base ${commit}).`);
  } else {
    writeFileSync(generated, output);
    console.log(`Regenerated retained local Hempi source (upstream base ${commit}); no checkout or network used.`);
  }
} else {
  const source = process.argv[2] ?? join(homedir(), "Work/hempi");
  const revision = process.argv[3] ?? "main";
  const commit = execFileSync("git", ["rev-parse", "--verify", `${revision}^{commit}`], { cwd: source, encoding: "utf8" }).trim();
  const archive = execFileSync("git", ["archive", "--format=tar", commit, "src", "prompts", "package.json", "OMP-LICENSE", "OPTCHAT-LICENSE", "NOTICE.md"], { cwd: source, maxBuffer: 32 * 1024 * 1024 });
  const stage = mkdtempSync(join(tmpdir(), "bb-hempi-source-"));
  try {
    execFileSync("tar", ["-xf", "-", "-C", stage], { input: archive });
    const output = embed(stage, commit);
    writeFileSync(join(stage, "REVISION"), `${commit}\n`);
    mkdirSync(dirname(vendor), { recursive: true });
    const replacement = `${vendor}.refresh-${process.pid}`;
    if (existsSync(replacement)) throw new Error(`Refresh staging directory already exists: ${replacement}`);
    cpSync(stage, replacement, { recursive: true });
    rmSync(vendor, { recursive: true, force: true });
    renameSync(replacement, vendor);
    writeFileSync(generated, output);
    console.log(`Bundled committed Hempi ${commit}; ${Buffer.byteLength(output)} embedded bytes.`);
  } finally {
    rmSync(stage, { recursive: true, force: true });
  }
}
