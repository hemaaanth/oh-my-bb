import { mkdir, readFile, writeFile } from "node:fs/promises";

// Use the same pinned dataset as server/emoji-data.ts, without shipping its labels in app.js.
const root = new URL("../", import.meta.url);
const source = await readFile(new URL("node_modules/emoji-picker-react/dist/data/emojis-en.ts", root), "utf8");
const match = /^const data = (\{.+\}) as unknown as EmojiData;$/m.exec(source);
if (!match) throw new Error("emoji-picker-react dataset format changed");
const dataset = JSON.parse(match[1]);
const single = new Map();
for (const entries of Object.values(dataset.emojis)) {
  for (const { u } of entries) {
    const points = u.split("-").map((part) => parseInt(part, 16));
    const base = points.filter((point) => point !== 0xfe0f);
    if (base.length !== 1 || (base[0] >= 0x1f1e6 && base[0] <= 0x1f1ff)) continue;
    // Retain the dataset's presentation selector (e.g. 🖊️, not text-style 🖊).
    single.set(base[0], String.fromCodePoint(...points));
  }
}
const emojis = [...single.entries()].sort(([a], [b]) => a - b).map(([, emoji]) => emoji);
const providers = "🤝 📊 🤖 🪄 🎨 🎬 📝 🖊️ 🤓 🤙 🌐 📣".split(" ");
await mkdir(new URL("shared/", root), { recursive: true });
await writeFile(new URL("shared/avatar-data.ts", root), `// Generated by scripts/generate-avatar-icons.mjs from emoji-picker-react.\nexport const avatarEmojis = ${JSON.stringify(emojis.join(" "))}.split(" ");\n\nexport const providerAvatarEmojis = ${JSON.stringify(providers.join(" "))}.split(" ");\n`);
await mkdir(new URL("assets/emoji/", root), { recursive: true });
for (const emoji of providers) {
  const codepoint = emoji.codePointAt(0).toString(16);
  // BB uses provider SVGs as alpha masks. Luminance preserves interior emoji detail.
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><mask id="emoji" maskUnits="userSpaceOnUse" x="0" y="0" width="32" height="32" style="mask-type:luminance"><text x="16" y="26" text-anchor="middle" font-size="28" fill="white" font-family="Apple Color Emoji, Segoe UI Emoji, Noto Color Emoji, sans-serif">${emoji}</text></mask><rect width="32" height="32" fill="white" mask="url(#emoji)"/></svg>\n`;
  await writeFile(new URL(`assets/emoji/${codepoint}.svg`, root), svg);
}
